<?php

namespace App\Http\Controllers\Api\Learning;

use App\Http\Controllers\Controller;
use App\Models\Center;
use App\Models\Course;
use App\Models\Lesson;
use App\Models\LessonAsset;
use App\Services\Learning\LearningAccessService;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\Rule;
use Throwable;

class LessonAssetManagementController extends Controller
{
    public function __construct(
        protected LearningAccessService $learningAccess
    ) {}

    /**
     * List all assets belonging to an authorized lesson.
     * Archived assets remain visible to administrators.
     */
    public function index(Request $request): JsonResponse
    {
        [, , $lesson] = $this->resolveLessonContext($request);

        $assets = $lesson->assets()
            ->forCenter($lesson->center_id)
            ->orderBy('sort_order')
            ->orderBy('id')
            ->get();

        return response()->json([
            'data' => $assets->map(
                fn (LessonAsset $asset): array => $this->assetPayload($asset)
            )->values(),
        ]);
    }

    /**
     * Upload a private image or document.
     *
     * Storage location and filename are always generated by the server.
     */
    public function store(Request $request): JsonResponse
    {
        [$center, , $lesson] = $this->resolveLessonContext($request);

        $assetType = (string) $request->input('asset_type');

        $rules = [
            'asset_type' => [
                'required',
                Rule::in([
                    LessonAsset::TYPE_IMAGE,
                    LessonAsset::TYPE_FILE,
                ]),
            ],

            'title' => [
                'nullable',
                'string',
                'max:255',
            ],

            'file' => [
                'required',
                'file',
            ],

            'alt_text' => [
                'nullable',
                'string',
                'max:255',
            ],

            'caption' => [
                'nullable',
                'string',
                'max:3000',
            ],

            'is_downloadable' => [
                'sometimes',
                'boolean',
            ],

            'sort_order' => [
                'sometimes',
                'integer',
                'min:0',
                'max:65535',
            ],

            // Clients must never control internal storage metadata.
            'storage_disk' => ['prohibited'],
            'storage_key' => ['prohibited'],
            'video_provider' => ['prohibited'],
            'provider_asset_id' => ['prohibited'],
            'external_url' => ['prohibited'],
        ];

        if ($assetType === LessonAsset::TYPE_IMAGE) {
            $rules['file'] = [
                'required',
                'file',
                'image',
                'mimes:jpg,jpeg,png,webp',
                'extensions:jpg,jpeg,png,webp',
                'max:'.config('learning.media.max_image_kb', 10240),
            ];

            $rules['alt_text'] = [
                'required',
                'string',
                'max:255',
            ];
        } else {
            $rules['file'] = [
                'required',
                'file',
                'mimes:pdf,txt,doc,docx,xls,xlsx,ppt,pptx',
                'extensions:pdf,txt,doc,docx,xls,xlsx,ppt,pptx',
                'max:'.config('learning.media.max_file_kb', 25600),
            ];
        }

        $validated = $request->validate($rules);

        /** @var UploadedFile $file */
        $file = $validated['file'];

        $diskName = (string) config(
            'learning.media.upload_disk',
            'private'
        );

        $allowedDisks = config(
            'learning.media.allowed_disks',
            ['private']
        );

        // Prevent arbitrary public or unconfigured storage destinations.
        abort_unless(
            in_array($diskName, $allowedDisks, true)
                && is_array(config("filesystems.disks.{$diskName}")),
            503,
            'Private learning storage is not configured.'
        );

        $directory = sprintf(
            'centers/%d/lessons/%d/assets',
            $center->id,
            $lesson->id
        );

        $storageKey = $file->store(
            $directory,
            [
                'disk' => $diskName,
                'visibility' => 'private',
            ]
        );

        abort_unless(
            is_string($storageKey) && $storageKey !== '',
            500,
            'Unable to store the uploaded resource.'
        );

        $originalFilename = $this->safeOriginalFilename($file);

        $sortOrder = $validated['sort_order']
            ?? ((int) $lesson->assets()->max('sort_order') + 1);

        try {
            $asset = DB::transaction(
                function () use (
                    $center,
                    $lesson,
                    $validated,
                    $file,
                    $diskName,
                    $storageKey,
                    $originalFilename,
                    $sortOrder
                ): LessonAsset {
                    $assetType = $validated['asset_type'];

                    return LessonAsset::query()->create([
                        'center_id' => $center->id,
                        'lesson_id' => $lesson->id,

                        'title' => $validated['title']
                            ?? pathinfo(
                                $originalFilename,
                                PATHINFO_FILENAME
                            ),

                        'asset_type' => $assetType,

                        'storage_disk' => $diskName,
                        'storage_key' => $storageKey,

                        'original_filename' => $originalFilename,
                        'mime_type' => $file->getMimeType(),
                        'size_bytes' => $file->getSize(),

                        'video_provider' => null,
                        'provider_asset_id' => null,
                        'external_url' => null,

                        'duration_seconds' => null,

                        'alt_text' => $validated['alt_text'] ?? null,
                        'caption' => $validated['caption'] ?? null,

                        'is_downloadable' => array_key_exists(
                            'is_downloadable',
                            $validated
                        )
                            ? filter_var(
                                $validated['is_downloadable'],
                                FILTER_VALIDATE_BOOLEAN
                            )
                            : $assetType === LessonAsset::TYPE_FILE,

                        'sort_order' => $sortOrder,

                        'status' => LessonAsset::STATUS_ACTIVE,
                    ]);
                }
            );
        } catch (Throwable $exception) {
            // Remove the file if database persistence fails.
            Storage::disk($diskName)->delete($storageKey);

            throw $exception;
        }

        return response()->json([
            'message' => 'Learning resource uploaded successfully.',
            'data' => $this->assetPayload($asset),
        ], 201);
    }

    /**
     * Update an asset's presentation and download metadata.
     */
    public function update(Request $request): JsonResponse
    {
        $lessonContext = $this->resolveLessonContext($request);
        $lesson = $lessonContext[2];

        $asset = $this->resolveAsset(
            $lesson,
            (string) $request->route('asset')
        );

        $validated = $request->validate([
            'title' => [
                'sometimes',
                'nullable',
                'string',
                'max:255',
            ],

            'alt_text' => [
                'sometimes',
                'nullable',
                'string',
                'max:255',
            ],

            'caption' => [
                'sometimes',
                'nullable',
                'string',
                'max:3000',
            ],

            'is_downloadable' => [
                'sometimes',
                'boolean',
            ],

            'sort_order' => [
                'sometimes',
                'integer',
                'min:0',
                'max:65535',
            ],
        ]);

        if (
            filter_var(
                $validated['is_downloadable'] ?? false,
                FILTER_VALIDATE_BOOLEAN
            )
            && ! in_array(
                $asset->asset_type,
                [
                    LessonAsset::TYPE_FILE,
                    LessonAsset::TYPE_IMAGE,
                ],
                true
            )
        ) {
            abort(
                422,
                'Downloading is not supported for this resource type.'
            );
        }

        $asset->fill($validated);
        $asset->save();

        return response()->json([
            'message' => 'Learning resource updated successfully.',
            'data' => $this->assetPayload($asset->refresh()),
        ]);
    }

    /**
     * Archive an asset without physically deleting its file.
     */
    public function archive(Request $request): JsonResponse
    {
        $lessonContext = $this->resolveLessonContext($request);
        $lesson = $lessonContext[2];

        $asset = $this->resolveAsset(
            $lesson,
            (string) $request->route('asset')
        );

        $asset->update([
            'status' => LessonAsset::STATUS_ARCHIVED,
        ]);

        return response()->json([
            'message' => 'Learning resource archived successfully.',
            'data' => $this->assetPayload($asset->refresh()),
        ]);
    }

    /**
     * Restore a previously archived resource.
     */
    public function restore(Request $request): JsonResponse
    {
        $lessonContext = $this->resolveLessonContext($request);
        $lesson = $lessonContext[2];

        $asset = $this->resolveAsset(
            $lesson,
            (string) $request->route('asset')
        );

        $this->ensureAssetStorageExists($asset);

        $asset->update([
            'status' => LessonAsset::STATUS_ACTIVE,
        ]);

        return response()->json([
            'message' => 'Learning resource restored successfully.',
            'data' => $this->assetPayload($asset->refresh()),
        ]);
    }

    /**
     * Resolve the active center, course and lesson context.
     *
     * @return array{0: Center, 1: Course, 2: Lesson}
     */
    private function resolveLessonContext(Request $request): array
    {
        $center = $request->attributes->get('current_center');

        abort_unless(
            $center instanceof Center,
            404,
            'Center not found.'
        );

        $user = $request->user();

        abort_unless(
            $user !== null
                && $this->learningAccess->isAdministrativeViewer(
                    $user,
                    $center
                ),
            403,
            'Administrative learning access is required.'
        );

        $courseParam = (string) $request->route('course');

        $courseQuery = Course::query()
            ->forCenter($center->id);

        if (ctype_digit($courseParam)) {
            $courseQuery->whereKey((int) $courseParam);
        } else {
            $courseQuery->where('slug', $courseParam);
        }

        $course = $courseQuery->firstOrFail();

        Gate::authorize(
            'viewLearning',
            [$course, $center]
        );

        $lessonParam = (string) $request->route('lesson');

        abort_unless(
            ctype_digit($lessonParam),
            404,
            'Lesson not found.'
        );

        $lesson = Lesson::query()
            ->forCenter($center->id)
            ->whereKey((int) $lessonParam)
            ->whereHas(
                'courseModule',
                function (Builder $query) use ($center, $course): void {
                    $query
                        ->forCenter($center->id)
                        ->where('course_id', $course->id);
                }
            )
            ->firstOrFail();

        Gate::authorize(
            'viewLearning',
            [$lesson, $course, $center]
        );

        return [$center, $course, $lesson];
    }

    /**
     * Resolve an asset strictly inside the requested lesson and tenant.
     */
    private function resolveAsset(
        Lesson $lesson,
        string $assetParam
    ): LessonAsset {
        abort_unless(
            ctype_digit($assetParam),
            404,
            'Asset not found.'
        );

        return LessonAsset::query()
            ->forCenter($lesson->center_id)
            ->where('lesson_id', $lesson->id)
            ->whereKey((int) $assetParam)
            ->firstOrFail();
    }

    /**
     * Verify that the underlying resource still exists before restoring it.
     */
    private function ensureAssetStorageExists(
        LessonAsset $asset
    ): void {
        if (
            in_array(
                $asset->asset_type,
                [
                    LessonAsset::TYPE_FILE,
                    LessonAsset::TYPE_IMAGE,
                ],
                true
            )
        ) {
            $allowedDisks = config(
                'learning.media.allowed_disks',
                ['private']
            );

            abort_unless(
                $asset->isPrivateStorageAsset()
                    && in_array(
                        $asset->storage_disk,
                        $allowedDisks,
                        true
                    ),
                409,
                'The private resource reference is invalid.'
            );

            abort_unless(
                Storage::disk($asset->storage_disk)
                    ->exists($asset->storage_key),
                409,
                'The resource file no longer exists.'
            );

            return;
        }

        if ($asset->asset_type === LessonAsset::TYPE_VIDEO) {
            abort_unless(
                $asset->isProviderVideo(),
                409,
                'The video provider reference is invalid.'
            );

            return;
        }

        if ($asset->asset_type === LessonAsset::TYPE_EXTERNAL_LINK) {
            abort_unless(
                filled($asset->external_url),
                409,
                'The external resource URL is missing.'
            );

            return;
        }

        abort(409, 'Unsupported resource type.');
    }

    /**
     * Return only metadata safe for administrative API responses.
     *
     * Storage keys and provider identifiers remain server-side.
     *
     * @return array<string, mixed>
     */
    private function assetPayload(LessonAsset $asset): array
    {
        return [
            'id' => $asset->id,
            'title' => $asset->title,
            'asset_type' => $asset->asset_type,
            'original_filename' => $asset->original_filename,
            'mime_type' => $asset->mime_type,
            'size_bytes' => $asset->size_bytes,
            'duration_seconds' => $asset->duration_seconds,
            'alt_text' => $asset->alt_text,
            'caption' => $asset->caption,
            'is_downloadable' => $asset->is_downloadable,
            'sort_order' => $asset->sort_order,
            'status' => $asset->status,
            'created_at' => $asset->created_at?->toIso8601String(),
            'updated_at' => $asset->updated_at?->toIso8601String(),
        ];
    }

    /**
     * Normalize the client filename for display only.
     */
    private function safeOriginalFilename(
        UploadedFile $file
    ): string {
        $filename = basename(
            str_replace(
                '\\',
                '/',
                $file->getClientOriginalName()
            )
        );

        $filename = preg_replace(
            '/[\x00-\x1F\x7F]/u',
            '_',
            $filename
        );

        return mb_substr(
            $filename ?: 'learning-resource',
            0,
            255
        );
    }
}
